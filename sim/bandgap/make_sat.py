#!/usr/bin/env python3
"""Write sat.spice (test 10) from the transistors in bandgap_core.spice.

Called by run_all.sh after netlisting, so the saturation check always covers every
MOSFET in the schematic with its current model name.
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
core = (here / "bandgap_core.spice").read_text()
devs = re.findall(r"(?m)^X(M\d+) .*?sky130_fd_pr__([np]fet_\w+)", core)

L = ["* 10. Saturation check: |VDS| against VDSAT for every transistor, at 1.8 V and 1.62 V supply.",
     "*     margin = |VDS| - VDSAT; a negative margin means the device has left saturation.",
     "*     Generated by make_sat.py from bandgap_core.spice. Set the temperature with .temp.",
     "*     (The start-up devices M9-M11 are switches and are expected to show odd values.)",
     ".include bench.spice", ".control"]
for vdd in ("1.8", "1.62"):
    L += [f"alter VSUP dc = {vdd}", "op",
          f'echo "VDD = {vdd} V: device |VDS| VDSAT margin |VGS| VTH ID(uA)"']
    for name, model in devs:
        p = f"@m.x1.x{name.lower()}.msky130_fd_pr__{model}"
        L += [f"let vds = abs({p}[vds])", f"let vdsat = {p}[vdsat]", "let marg = vds - vdsat",
              f"let vgs = abs({p}[vgs])", f"let vth = abs({p}[vth])", f"let id = abs({p}[id]) * 1e6",
              f'echo "sat {vdd} {name} $&vds $&vdsat $&marg $&vgs $&vth $&id"']
L += [".endc", ".end"]
(here / "sat.spice").write_text("\n".join(L) + "\n")
